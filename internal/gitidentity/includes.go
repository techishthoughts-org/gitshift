package gitidentity

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/techishthoughts/gitshift/internal/models"
)

// Include is one managed includeIf entry: repositories under Dir use File.
type Include struct {
	Dir, Account, File string
}

// Key is the global Git config key for the entry. The trailing slash makes
// gitdir match every repository below Dir.
func (i Include) Key() string {
	return "includeIf.gitdir:" + filepath.ToSlash(i.Dir) + "/.path"
}

// Plan returns the includes for cfg's auto-switch rules, ordered so a deeper
// directory's include comes later and therefore wins.
func Plan(cfg *models.Config, includeDir string) []Include {
	includes := make([]Include, 0, len(cfg.AutoSwitch.Rules))
	for _, rule := range cfg.AutoSwitch.Rules {
		if _, ok := cfg.Accounts[rule.Account]; !ok {
			continue
		}
		includes = append(includes, Include{
			Dir:     filepath.Clean(rule.Path),
			Account: rule.Account,
			File:    filepath.Join(includeDir, rule.Account+".gitconfig"),
		})
	}
	sort.SliceStable(includes, func(a, b int) bool {
		depthA, depthB := strings.Count(includes[a].Dir, string(filepath.Separator)), strings.Count(includes[b].Dir, string(filepath.Separator))
		if depthA != depthB {
			return depthA < depthB
		}
		return includes[a].Dir < includes[b].Dir
	})
	return includes
}

// Sync writes one include file per account that a rule uses, removes include
// files no rule uses, and makes the managed includeIf entries the last entries
// of the global Git config so they override the global identity.
func Sync(cfg *models.Config, includeDir string) error {
	includes := Plan(cfg, includeDir)
	if err := os.MkdirAll(includeDir, 0o700); err != nil {
		return fmt.Errorf("create %s: %w", includeDir, err)
	}
	wanted := map[string]bool{}
	for _, include := range includes {
		if wanted[include.File] {
			continue
		}
		wanted[include.File] = true
		if err := writeIncludeFile(cfg.Accounts[include.Account], include.File); err != nil {
			return err
		}
	}
	if err := removeStaleFiles(includeDir, wanted); err != nil {
		return err
	}
	return syncEntries(includes, includeDir)
}

// Remove deletes every managed includeIf entry and include file.
func Remove(includeDir string) error {
	if err := syncEntries(nil, includeDir); err != nil {
		return err
	}
	return removeStaleFiles(includeDir, nil)
}

// Installed returns the managed includeIf entries in global config order.
func Installed(includeDir string) ([]Include, error) {
	entries, err := globalEntries()
	if err != nil {
		return nil, err
	}
	var installed []Include
	for _, entry := range entries {
		if include, ok := managedInclude(entry, includeDir); ok {
			installed = append(installed, include)
		}
	}
	return installed, nil
}

func writeIncludeFile(account *models.Account, path string) error {
	settings, err := IdentitySettings(account)
	if err != nil {
		return fmt.Errorf("account %s: %w", account.Alias, err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".gitshift-include-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if _, err := fmt.Fprintf(tmp, "# Generated by gitshift for account %q. Do not edit; changes are overwritten.\n", account.Alias); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	// git config writes the file so values are quoted exactly as Git reads them.
	for _, setting := range settings {
		if output, err := exec.Command("git", "config", "--file", tmpName, setting.Key, setting.Value).CombinedOutput(); err != nil {
			return fmt.Errorf("write %s for %s: %w: %s", setting.Key, account.Alias, err, strings.TrimSpace(string(output)))
		}
	}
	rendered, err := os.ReadFile(tmpName)
	if err != nil {
		return err
	}
	if current, err := os.ReadFile(path); err == nil && bytes.Equal(current, rendered) {
		return nil
	}
	return os.Rename(tmpName, path)
}

func removeStaleFiles(includeDir string, keep map[string]bool) error {
	files, err := filepath.Glob(filepath.Join(includeDir, "*.gitconfig"))
	if err != nil {
		return err
	}
	for _, file := range files {
		if keep[file] {
			continue
		}
		if err := os.Remove(file); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
	}
	return nil
}

type configEntry struct{ key, value string }

// globalEntries lists the global Git config in file order. A missing global
// config file is empty.
func globalEntries() ([]configEntry, error) {
	output, err := exec.Command("git", "config", "--global", "--list", "-z").Output()
	if err != nil {
		var exitErr *exec.ExitError
		if errors.As(err, &exitErr) && len(output) == 0 {
			return nil, nil
		}
		return nil, fmt.Errorf("read global Git config: %w", err)
	}
	var entries []configEntry
	for _, record := range strings.Split(string(output), "\x00") {
		if record == "" {
			continue
		}
		key, value, _ := strings.Cut(record, "\n")
		entries = append(entries, configEntry{key, value})
	}
	return entries, nil
}

// managedInclude recognises an includeIf.gitdir entry that points into
// includeDir. Git lowercases the section name but keeps the subsection.
func managedInclude(entry configEntry, includeDir string) (Include, bool) {
	const prefix, suffix = "includeif.gitdir:", "/.path"
	if !strings.HasPrefix(entry.key, prefix) || !strings.HasSuffix(entry.key, suffix) {
		return Include{}, false
	}
	if filepath.Dir(entry.value) != filepath.Clean(includeDir) || !strings.HasSuffix(entry.value, ".gitconfig") {
		return Include{}, false
	}
	dir := filepath.FromSlash(strings.TrimSuffix(strings.TrimPrefix(entry.key, prefix), suffix))
	return Include{Dir: dir, Account: strings.TrimSuffix(filepath.Base(entry.value), ".gitconfig"), File: entry.value}, true
}

func syncEntries(wanted []Include, includeDir string) error {
	entries, err := globalEntries()
	if err != nil {
		return err
	}
	var installed []Include
	for _, entry := range entries {
		if include, ok := managedInclude(entry, includeDir); ok {
			installed = append(installed, include)
		}
	}
	// Already correct when the managed entries are exactly the wanted ones,
	// in order, at the very end of the file.
	if len(installed) == len(wanted) && len(entries) >= len(wanted) {
		inPlace := true
		tail := entries[len(entries)-len(wanted):]
		for i, include := range wanted {
			got, ok := managedInclude(tail[i], includeDir)
			if !ok || got != include {
				inPlace = false
				break
			}
		}
		if inPlace {
			return nil
		}
	}
	for _, include := range installed {
		valuePattern := "^" + regexp.QuoteMeta(include.File) + "$"
		if output, err := exec.Command("git", "config", "--global", "--unset-all", include.Key(), valuePattern).CombinedOutput(); err != nil {
			return fmt.Errorf("remove include for %s: %w: %s", include.Dir, err, strings.TrimSpace(string(output)))
		}
	}
	for _, include := range wanted {
		if output, err := exec.Command("git", "config", "--global", "--add", include.Key(), include.File).CombinedOutput(); err != nil {
			return fmt.Errorf("add include for %s: %w: %s", include.Dir, err, strings.TrimSpace(string(output)))
		}
	}
	return nil
}
