// generatedHeader starts every include file GitShift writes. Only files that
// start with it are ever deleted, so other files in the directory are safe.
const generatedHeader = "# Generated by gitshift"

// Include is one managed includeIf entry: repositories under Dir use File.
type Include struct {
	Dir, Account, File string
}

// condition is case-insensitive where the default file system is, so a rule
// stored with different capitalisation than the disk still matches.
func condition() string {
	if runtime.GOOS == "darwin" || runtime.GOOS == "windows" {
		return "gitdir/i:"
	}
	return "gitdir:"
}

// globEscaper escapes characters that gitdir patterns treat as wildcards.
var globEscaper = strings.NewReplacer(`\`, `\\`, `*`, `\*`, `?`, `\?`, `[`, `\[`)

// Key is the global Git config key for the entry. The trailing slash makes
// gitdir match every repository below Dir.
func (i Include) Key() string {
	return "includeIf." + condition() + globEscaper.Replace(filepath.ToSlash(i.Dir)) + "/.path"
}

// listedKey is Key as `git config --list` prints it: Git lowercases the
// section and variable names but keeps the subsection.
func (i Include) listedKey() string {
	return "includeif." + strings.TrimSuffix(strings.TrimPrefix(i.Key(), "includeIf."), ".path") + ".path"
}

// Plan returns the includes for cfg's auto-switch rules, ordered so a deeper
// directory's include comes later and therefore wins.
func Plan(cfg *models.Config, includeDir string) []Include {
	includes := make([]Include, 0, len(cfg.AutoSwitch.Rules))
	for _, rule := range cfg.AutoSwitch.Rules {
		if _, ok := cfg.Accounts[rule.Account]; !ok {
			continue
		}
		includes = append(includes, Include{
			Dir:     filepath.Clean(rule.Path),
			Account: rule.Account,
			File:    filepath.Join(includeDir, rule.Account+".gitconfig"),
		})
	}
	sort.SliceStable(includes, func(a, b int) bool {
		depthA, depthB := strings.Count(includes[a].Dir, string(filepath.Separator)), strings.Count(includes[b].Dir, string(filepath.Separator))
		if depthA != depthB {
			return depthA < depthB
		}
		return includes[a].Dir < includes[b].Dir
	})
	return includes
}

// Sync makes the global Git config match cfg's rules. It renders every
// include file first and fails before changing anything if one cannot be
// built, then installs the files, then rewrites the includeIf entries so they
// are the last entries of the global config, and only then deletes include
// files that no rule uses any more.
func Sync(cfg *models.Config, includeDir string) error {
	includes := Plan(cfg, includeDir)
	if err := os.MkdirAll(includeDir, 0o700); err != nil {
		return fmt.Errorf("create %s: %w", includeDir, err)
	}
	rendered := map[string][]byte{}
	for _, include := range includes {
		if _, done := rendered[include.File]; done {
			continue
		}
		content, err := renderIncludeFile(cfg.Accounts[include.Account], includeDir)
		if err != nil {
			return err
		}
		rendered[include.File] = content
	}
	for path, content := range rendered {
		if err := installFile(path, content); err != nil {
			return err
		}
	}
	if err := syncEntries(includes, includeDir); err != nil {
		return err
	}
	keep := map[string]bool{}
	for path := range rendered {
		keep[path] = true
	}
	return removeGeneratedFiles(includeDir, keep)
}

// Remove deletes every managed includeIf entry, then the include files.
func Remove(includeDir string) error {
	if err := syncEntries(nil, includeDir); err != nil {
		return err
	}
	return removeGeneratedFiles(includeDir, nil)
}

// Installed returns the managed includeIf entries in global config order.
func Installed(includeDir string) ([]Include, error) {
	entries, err := globalEntries()
	if err != nil {
		return nil, err
	}
	return managedIncludes(entries, includeDir), nil
}

// InSync reports whether the global config holds exactly the planned
// entries, in order, as its last entries.
func InSync(cfg *models.Config, includeDir string) (bool, error) {
	entries, err := globalEntries()
	if err != nil {
		return false, err
	}
	return inPlace(entries, Plan(cfg, includeDir), includeDir), nil
}

// renderIncludeFile writes the account's settings with `git config --file`
// into a scratch file, so values are quoted exactly as Git reads them.
func renderIncludeFile(account *models.Account, includeDir string) ([]byte, error) {
	settings, err := IdentitySettings(account)
	if err != nil {
		return nil, fmt.Errorf("account %s: %w", account.Alias, err)
	}
	scratch, err := os.CreateTemp(includeDir, ".gitshift-render-*")
	if err != nil {
		return nil, err
	}
	name := scratch.Name()
	defer os.Remove(name)
	if _, err := fmt.Fprintf(scratch, "%s for account %q. Do not edit; changes are overwritten.\n", generatedHeader, account.Alias); err != nil {
		scratch.Close()
		return nil, err
	}
	if err := scratch.Close(); err != nil {
		return nil, err
	}
	for _, setting := range settings {
		if output, err := exec.Command("git", "config", "--file", name, setting.Key, setting.Value).CombinedOutput(); err != nil {
			return nil, fmt.Errorf("render %s for %s: %w: %s", setting.Key, account.Alias, err, strings.TrimSpace(string(output)))
		}
	}
	return os.ReadFile(name)
}

func installFile(path string, content []byte) error {
	if current, err := os.ReadFile(path); err == nil && bytes.Equal(current, content) {
		return nil
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".gitshift-include-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

// removeGeneratedFiles deletes include files GitShift wrote that are not in
// keep. Files without the generated header are never touched.
func removeGeneratedFiles(includeDir string, keep map[string]bool) error {
	files, err := filepath.Glob(filepath.Join(includeDir, "*.gitconfig"))
	if err != nil {
		return err
	}
	for _, file := range files {
		if keep[file] || !isGenerated(file) {
			continue
		}
		if err := os.Remove(file); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
	}
	return nil
}

func isGenerated(path string) bool {
	file, err := os.Open(path)
	if err != nil {
		return false
	}
	defer file.Close()
	line, err := bufio.NewReader(file).ReadString('\n')
	return (err == nil || len(line) > 0) && strings.HasPrefix(line, generatedHeader)
}

type configEntry struct{ key, value string }

// globalEntries lists the global Git config in file order. A missing global
// config file is empty.
func globalEntries() ([]configEntry, error) {
	output, err := exec.Command("git", "config", "--global", "--list", "-z").Output()
	if err != nil {
		var exitErr *exec.ExitError
		if errors.As(err, &exitErr) && len(output) == 0 {
			return nil, nil
		}
		return nil, fmt.Errorf("read global Git config: %w", err)
	}
	var entries []configEntry
	for _, record := range strings.Split(string(output), "\x00") {
		if record == "" {
			continue
		}
		key, value, _ := strings.Cut(record, "\n")
		entries = append(entries, configEntry{key, value})
	}
	return entries, nil
}

// managedIncludes returns entries whose path points to an include file in
// includeDir, whatever their condition, so stale gitdir/gitdir/i entries are
// recognised too.
func managedIncludes(entries []configEntry, includeDir string) []Include {
	var managed []Include
	for _, entry := range entries {
		if !strings.HasPrefix(entry.key, "includeif.") || !strings.HasSuffix(entry.key, ".path") {
			continue
		}
		if filepath.Dir(entry.value) != filepath.Clean(includeDir) || !strings.HasSuffix(entry.value, ".gitconfig") {
			continue
		}
		subsection := strings.TrimSuffix(strings.TrimPrefix(entry.key, "includeif."), ".path")
		pattern := strings.TrimPrefix(strings.TrimPrefix(subsection, "gitdir/i:"), "gitdir:")
		dir := filepath.FromSlash(strings.TrimSuffix(unescapeGlob(pattern), "/"))
		managed = append(managed, Include{Dir: dir, Account: strings.TrimSuffix(filepath.Base(entry.value), ".gitconfig"), File: entry.value})
	}
	return managed
}

func unescapeGlob(pattern string) string {
	var b strings.Builder
	for i := 0; i < len(pattern); i++ {
		if pattern[i] == '\\' && i+1 < len(pattern) {
			i++
		}
		b.WriteByte(pattern[i])
	}
	return b.String()
}

// inPlace reports whether the last entries are exactly wanted, in order, and
// no other managed entry exists.
func inPlace(entries []configEntry, wanted []Include, includeDir string) bool {
	if len(managedIncludes(entries, includeDir)) != len(wanted) || len(entries) < len(wanted) {
		return false
	}
	tail := entries[len(entries)-len(wanted):]
	for i, include := range wanted {
		if tail[i].key != include.listedKey() || tail[i].value != include.File {
			return false
		}
	}
	return true
}

func syncEntries(wanted []Include, includeDir string) error {
	entries, err := globalEntries()
	if err != nil {
		return err
	}
	if inPlace(entries, wanted, includeDir) {
		return nil
	}
	removed := map[configEntry]bool{}
	for _, entry := range entries {
		if removed[entry] || len(managedIncludes([]configEntry{entry}, includeDir)) == 0 {
			continue
		}
		removed[entry] = true // --unset-all drops every duplicate at once
		key := "includeIf." + strings.TrimPrefix(entry.key, "includeif.")
		valuePattern := "^" + regexp.QuoteMeta(entry.value) + "$"
		if output, err := exec.Command("git", "config", "--global", "--unset-all", key, valuePattern).CombinedOutput(); err != nil {
			return fmt.Errorf("remove include %s: %w: %s", key, err, strings.TrimSpace(string(output)))
		}
	}
	for _, include := range wanted {
		if output, err := exec.Command("git", "config", "--global", "--add", include.Key(), include.File).CombinedOutput(); err != nil {
			return fmt.Errorf("add include for %s: %w: %s", include.Dir, err, strings.TrimSpace(string(output)))
		}
	}
	return nil
}
