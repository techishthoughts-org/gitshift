// Command gendocs writes the Markdown command reference from the cobra tree,
// so docs/reference always matches the real commands and flags.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra/doc"
	"github.com/techishthoughts/gitshift/cmd"
)

func main() {
	dir := "docs/reference/commands"
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	if err := generate(dir); err != nil {
		fmt.Fprintf(os.Stderr, "gendocs: %v\n", err)
		os.Exit(1)
	}
}

func generate(dir string) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	root := cmd.Root()
	root.DisableAutoGenTag = true
	prepender := func(string) string {
		return "<!-- Generated by `make docs` from the command definitions. Do not edit. -->\n\n"
	}
	linker := func(name string) string { return strings.ToLower(filepath.Base(name)) }
	return doc.GenMarkdownTreeCustom(root, dir, prepender, linker)
}
